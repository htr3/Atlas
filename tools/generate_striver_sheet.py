"""Generate the Atlas Striver Sheet course from the Java notes PDF."""

from __future__ import annotations

import json
import re
from pathlib import Path

from pypdf import PdfReader


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "raw data" / "Striver-180-Java-Notes.pdf"
OUTPUT = ROOT / "site" / "data" / "striver" / "striver-sheet.js"

MODULES = [
    (1, "Arrays"),
    (19, "Hashing"),
    (27, "Binary Search"),
    (41, "Sliding Window and Two Pointers"),
    (53, "Recursion and Backtracking"),
    (65, "Linked List"),
    (79, "Stack and Queues"),
    (95, "Greedy"),
    (107, "Heaps"),
    (117, "Binary Trees"),
    (132, "Binary Search Trees"),
    (142, "Graphs"),
    (169, "Dynamic Programming"),
    (192, "Tries"),
    (199, "Strings"),
    (212, "Bit Manipulation"),
    (222, "Mathematics"),
]
MODULE_NAMES = {name for _, name in MODULES}
APPROACH_LABELS = {
    "Brute force",
    "Brute",
    "Better",
    "Memoization",
    "Tabulation",
    "Optimal",
}


def module_for(problem_id: int) -> str:
    return next(
        name
        for index, (start, name) in enumerate(MODULES)
        if start <= problem_id and (index == len(MODULES) - 1 or problem_id < MODULES[index + 1][0])
    )


def clean_lines(value: str) -> list[str]:
    lines = []
    for line in value.replace("\ufffd", "—").splitlines():
        stripped = line.strip()
        if re.fullmatch(r"-- \d+ of \d+ --", stripped):
            continue
        if re.fullmatch(r"\d{1,3}", stripped):
            continue
        lines.append(line.rstrip())
    return lines


def parse_approaches(lines: list[str]) -> list[dict[str, str]]:
    starts = [index for index, line in enumerate(lines) if line.strip() in APPROACH_LABELS]
    approaches = []
    for position, start in enumerate(starts):
        end = starts[position + 1] if position + 1 < len(starts) else len(lines)
        label = lines[start].strip()
        block = [line for line in lines[start + 1 : end] if line.strip()]
        complexity_index = next(
            (index for index, line in enumerate(block) if line.strip().startswith("Complexity:")),
            len(block),
        )
        explanation = " ".join(line.strip() for line in block[:complexity_index])
        complexity = (
            block[complexity_index].strip().removeprefix("Complexity:").strip()
            if complexity_index < len(block)
            else ""
        )
        code = "\n".join(block[complexity_index + 1 :]).strip()
        approaches.append(
            {
                "label": label,
                "explanation": explanation,
                "complexity": complexity,
                "code": code,
            }
        )
    return approaches


def extract_problems() -> list[dict]:
    text = "\n".join(page.extract_text() or "" for page in PdfReader(SOURCE).pages)
    matches = list(re.finditer(r"(?m)^(\d+)\.\s+(.+?)\s*$", text))
    problems = []
    for index, match in enumerate(matches):
        problem_id = int(match.group(1))
        if not 1 <= problem_id <= 229:
            continue
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        lines = clean_lines(text[match.end() : end])
        next_module = next(
            (line_index for line_index, line in enumerate(lines) if line.strip() in MODULE_NAMES),
            len(lines),
        )
        approaches = parse_approaches(lines[:next_module])
        if not approaches:
            raise ValueError(f"No approaches found for problem {problem_id}: {match.group(2)}")
        problems.append(
            {
                "id": problem_id,
                "title": match.group(2).replace("\ufffd", "—").strip(),
                "module": module_for(problem_id),
                "approaches": approaches,
            }
        )
    if [problem["id"] for problem in problems] != list(range(1, 230)):
        raise ValueError("Expected exactly the 229 consecutively numbered problems")
    return problems


def javascript(problems: list[dict]) -> str:
    payload = json.dumps(problems, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by tools/generate_striver_sheet.py from Striver-180-Java-Notes.pdf.
(() => {{
  const problems = {payload};
  const escapeHtml = (value = "") => value.replace(/[&<>"']/g, (character) => ({{
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;"
  }}[character]));

  window.LECTURES = window.LECTURES || [];
  problems.forEach((problem) => {{
    const approaches = problem.approaches;
    const last = approaches[approaches.length - 1];
    const xs = approaches.map((_, index) => (index - (approaches.length - 1) / 2) * 4.2);
    window.LECTURES.push({{
      course: "striver",
      id: problem.id,
      title: problem.title,
      category: problem.module,
      tagline: approaches.map((approach) => approach.label).join(" → "),
      summary: approaches[0].explanation,
      theory: approaches.map((approach) => ({{
        heading: approach.label,
        body: [
          `<span>${{escapeHtml(approach.explanation)}}</span>`,
          approach.complexity ? `<strong class="complexity">Complexity: ${{escapeHtml(approach.complexity)}}</strong>` : "",
          approach.code ? `<pre><code>${{escapeHtml(approach.code)}}</code></pre>` : ""
        ].filter(Boolean).join("")
      }})),
      keyTerms: approaches.map((approach) => ({{
        term: approach.label,
        def: approach.complexity || "See the explanation and Java implementation."
      }})),
      tradeoffs: approaches.length > 1 ? [{{
        pro: `${{last.label}} reaches ${{last.complexity || "the preferred solution"}}.`,
        con: `${{approaches[0].label}} is easier to derive, but usually costs more time or space.`
      }}] : [],
      interviewTips: [
        `Start with the ${{approaches[0].label.toLowerCase()}} idea, then explain what makes it expensive.`,
        `State the final complexity: ${{last.complexity || "derive it from the implementation"}}.`,
        "Code the Java function only after naming the invariant or recurrence."
      ],
      scene: {{
        nodes: [
          {{ id: "problem", label: problem.title, type: "note", pos: [0, 0, -5.2], showAt: 0 }},
          ...approaches.map((approach, index) => ({{
            id: `approach-${{index}}`,
            label: approach.label,
            type: index === approaches.length - 1 ? "worker" : "server",
            pos: [xs[index], 0, 1.2],
            showAt: index
          }}))
        ],
        edges: approaches.slice(1).map((_, index) => ({{
          from: `approach-${{index}}`,
          to: `approach-${{index + 1}}`,
          label: "improve",
          showAt: index + 1
        }})),
        steps: approaches.map((approach, index) => ({{
          title: approach.label,
          text: `${{approach.explanation}}${{approach.complexity ? ` Complexity: ${{approach.complexity}}` : ""}}`,
          highlight: [`approach-${{index}}`],
          flows: index ? [{{ from: `approach-${{index - 1}}`, to: `approach-${{index}}`, label: "optimize" }}] : []
        }}))
      }}
    }});
  }});
}})();
"""


def main() -> None:
    problems = extract_problems()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(javascript(problems), encoding="utf-8")
    print(f"Wrote {len(problems)} problems to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
